import type { FirewallRule } from './rules.ts'
import type { PortEntry } from '../data/ports.ts'
import { PORTS } from '../data/ports.ts'

function lookupPort(portStr: string): PortEntry | undefined {
  const n = Number(String(portStr).split(/[,-]/)[0])
  if (!Number.isFinite(n)) return undefined
  return PORTS.find((p) => p.port === n)
}

export function exportMarkdown(rules: FirewallRule[], title = 'Firewall Rule Documentation'): string {
  const now = new Date().toISOString().slice(0, 10)
  const lines: string[] = [
    `# ${title}`,
    '',
    `Generated by **PortForge** on ${now}`,
    '',
    '> Review conflicts and change-control approvals before implementing in production.',
    '',
    '## Rule summary',
    '',
    '| # | Name | Action | Dir | Proto | Port | Source | Destination |',
    '|---|------|--------|-----|-------|------|--------|-------------|',
  ]

  rules.forEach((r, i) => {
    lines.push(
      `| ${i + 1} | ${r.name} | ${r.action.toUpperCase()} | ${r.direction} | ${r.protocol} | ${r.port} | \`${r.source || 'any'}\` | \`${r.destination || 'any'}\` |`,
    )
  })

  lines.push('', '## Detailed rules', '')

  rules.forEach((r, i) => {
    const meta = lookupPort(r.port)
    lines.push(`### ${i + 1}. ${r.name}`)
    lines.push('')
    lines.push('```')
    lines.push(`${r.action.toUpperCase()} ${r.direction}`)
    lines.push(`  protocol : ${r.protocol}`)
    lines.push(`  port     : ${r.port}${meta ? ` (${meta.service})` : ''}`)
    lines.push(`  source   : ${r.source || 'any'}`)
    lines.push(`  dest     : ${r.destination || 'any'}`)
    lines.push('```')
    if (meta) {
      lines.push('')
      lines.push(`- **Service risk:** ${meta.risk}`)
      lines.push(`- **Guidance:** ${meta.guidance}`)
    }
    if (r.notes) {
      lines.push(`- **Notes:** ${r.notes}`)
    }
    lines.push('')
  })

  lines.push('## Implementation checklist')
  lines.push('')
  lines.push('- [ ] Peer review / CAB approval')
  lines.push('- [ ] Conflict review completed in PortForge')
  lines.push('- [ ] Rollback plan documented')
  lines.push('- [ ] Monitoring / logging verified')
  lines.push('- [ ] Change window scheduled')
  lines.push('')

  return lines.join('\n')
}

export function exportCsv(rules: FirewallRule[]): string {
  const header = ['name', 'action', 'direction', 'protocol', 'port', 'source', 'destination', 'notes']
  const rows = rules.map((r) =>
    [r.name, r.action, r.direction, r.protocol, r.port, r.source, r.destination, r.notes]
      .map((v) => `"${String(v).replace(/"/g, '""')}"`)
      .join(','),
  )
  return [header.join(','), ...rows].join('\n')
}

export function exportIptables(rules: FirewallRule[]): string {
  const lines = [
    '# Generated by PortForge — review before apply',
    '# Example iptables filter rules (INPUT/OUTPUT simplified)',
    '',
  ]
  rules.forEach((r) => {
    const chain = r.direction === 'outbound' ? 'OUTPUT' : 'INPUT'
    const target = r.action === 'allow' ? 'ACCEPT' : r.action === 'reject' ? 'REJECT' : 'DROP'
    const proto = r.protocol === 'TCP/UDP' || r.protocol === 'ANY' ? 'tcp' : r.protocol.toLowerCase()
    const port = r.port.includes('-') ? `${r.port.replace('-', ':')}` : r.port
    const src = r.source && r.source.toLowerCase() !== 'any' ? `-s ${r.source}` : ''
    const dst = r.destination && r.destination.toLowerCase() !== 'any' ? `-d ${r.destination}` : ''
    lines.push(`# ${r.name}`)
    lines.push(
      `iptables -A ${chain} ${src} ${dst} -p ${proto} --dport ${port} -j ${target}`.replace(/\s+/g, ' ').trim(),
    )
    if (r.protocol === 'TCP/UDP') {
      lines.push(
        `iptables -A ${chain} ${src} ${dst} -p udp --dport ${port} -j ${target}`.replace(/\s+/g, ' ').trim(),
      )
    }
    lines.push('')
  })
  return lines.join('\n')
}

export function exportAsa(rules: FirewallRule[]): string {
  const lines = ['! Generated by PortForge — Cisco ASA-style sketch', '! Validate objects/ACLs in lab first', '']
  rules.forEach((r, i) => {
    const action = r.action === 'allow' ? 'permit' : 'deny'
    const proto = r.protocol === 'ANY' ? 'ip' : r.protocol === 'TCP/UDP' ? 'tcp' : r.protocol.toLowerCase()
    const src = r.source && r.source.toLowerCase() !== 'any' ? r.source : 'any'
    const dst = r.destination && r.destination.toLowerCase() !== 'any' ? r.destination : 'any'
    lines.push(`! ${r.name}`)
    lines.push(`access-list PORTFORGE_ACL extended ${action} ${proto} ${src} ${dst} eq ${r.port.split(',')[0]}`)
    if (r.protocol === 'TCP/UDP') {
      lines.push(`access-list PORTFORGE_ACL extended ${action} udp ${src} ${dst} eq ${r.port.split(',')[0]}`)
    }
    lines.push(`! object suggestion: obj-rule-${i + 1}`)
    lines.push('')
  })
  return lines.join('\n')
}
